// Writes docs/phase-2/source-issues.md: every inconsistency or doubtful item flagged while extracting
// each original page (src/data/extracted/**/*.json → issues[]). For review by the business.
// Usage: node scripts/source-issues.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const dirs = [path.join(root, 'src', 'data', 'extracted'), path.join(root, 'src', 'data', 'extracted', 'pages')];
let md = '# Source content issues (per original page)\n\nFlagged during extraction of the Phase 1 page captures. None of these were silently "fixed": disputed facts were omitted or marked as awaiting confirmation on the rebuilt pages. Generated by `scripts/source-issues.mjs`.\n\n';
let total = 0;
for (const dir of dirs) {
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
    const j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    const issues = j.issues || [];
    if (!issues.length) continue;
    total += issues.length;
    md += `## ${j.title || f}\n\n\`${j.path || f}\` · source \`${j.sourceFile || 'n/a'}\`\n\n${issues.map((i) => `- ${i}`).join('\n')}\n\n`;
  }
}
fs.mkdirSync(path.join(root, 'docs', 'phase-2'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'phase-2', 'source-issues.md'), md);
console.log(`source-issues.md: ${total} issues`);
